"""Generate the herascrape endpoint mixins and types from ``openapi.json``.

Run as ``python -m codegen.generate`` from the repo root. The output is
deterministic and ruff-formatted; CI re-runs it and fails on any diff.
"""

import json
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .names import PATH_METHOD_NAMES

_HERE = Path(__file__).resolve().parent
_REPO_ROOT = _HERE.parent
OPENAPI_PATH = _REPO_ROOT / "openapi.json"
PACKAGE_DIR = _REPO_ROOT / "python" / "herascrape"
JS_SRC_DIR = _REPO_ROOT / "js" / "src"

HEADER = "# generated by codegen/generate.py — do not edit\n"
TS_HEADER = "// generated by codegen/generate.py — do not edit"

PRETTIER_BIN = _REPO_ROOT / "js" / "node_modules" / ".bin" / "prettier"
_PRETTIER_CONFIG = _REPO_ROOT / "js" / ".prettierrc.json"

_PY_TO_TS = {
    "str": "string",
    "int": "number",
    "float": "number",
    "bool": "boolean",
}
_TS_RETURN_TYPES = {
    "resolve_media": "MediaIdResolution",
    "balance": "BalanceResponse",
}
_TS_RESULT = "Record<string, unknown>"
_TS_OUTPUT_FILES = ("types.ts", "endpoints.ts")

_SESSION_ID_PARAMS = frozenset(
    {"search_session_id", "serp_session_id", "browse_session_id"}
)
_TYPE_MAP = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
}
_RETURN_TYPES = {
    "resolve_media": "MediaIdResolution",
    "balance": "BalanceResponse",
}

# Cursor endpoints returning a raw feed dict, not a Page; no iter_.
_NON_PAGE_CURSOR_ENDPOINTS = frozenset({"user_posts"})

_OUTPUT_FILES = ("types.py", "_endpoints_sync.py", "_endpoints_async.py")


@dataclass(frozen=True)
class Param:
    name: str
    base_type: str
    required: bool
    is_session_id: bool


@dataclass(frozen=True)
class Endpoint:
    path: str
    name: str
    summary: str
    path_params: tuple[Param, ...]
    query_params: tuple[Param, ...]
    paginable: bool
    item_key: str
    return_type: str


def _base_type(schema: dict[str, Any]) -> str:
    """The Python base type for a parameter schema, unwrapping anyOf nulls."""
    if "anyOf" in schema:
        for member in schema["anyOf"]:
            if member.get("type") != "null":
                return _base_type(member)
    return _TYPE_MAP[schema["type"]]


def _query_param(spec: dict[str, Any]) -> Param:
    name = spec["name"]
    is_session_id = name in _SESSION_ID_PARAMS
    required = bool(spec.get("required", False)) and not is_session_id
    return Param(
        name=name,
        base_type=_base_type(spec["schema"]),
        required=required,
        is_session_id=is_session_id,
    )


def _build_endpoints() -> list[Endpoint]:
    spec: dict[str, Any] = json.loads(OPENAPI_PATH.read_text(encoding="utf-8"))
    endpoints: list[Endpoint] = []
    for path, item in spec["paths"].items():
        get = item["get"]
        params = get.get("parameters", [])
        path_params = tuple(
            Param(
                name=p["name"],
                base_type=_base_type(p["schema"]),
                required=True,
                is_session_id=False,
            )
            for p in params
            if p["in"] == "path"
        )
        query_params = tuple(
            _query_param(p) for p in params if p["in"] == "query"
        )
        name = PATH_METHOD_NAMES[path]
        endpoints.append(
            Endpoint(
                path=path,
                name=name,
                summary=get.get("summary") or name,
                path_params=path_params,
                query_params=query_params,
                paginable=any(p.name == "cursor" for p in query_params),
                item_key="edges" if name == "search_top" else "items",
                return_type=_RETURN_TYPES.get(name, "Any"),
            )
        )
    return endpoints


def _annot(param: Param) -> str:
    if param.required:
        return f"{param.name}: {param.base_type}"
    return f"{param.name}: Optional[{param.base_type}] = None"


def _path_expr(ep: Endpoint) -> str:
    if ep.path_params:
        return f'f"{ep.path}"'
    return f'"{ep.path}"'


def _params_dict(query_params: tuple[Param, ...]) -> str:
    body = ", ".join(f'"{p.name}": {p.name}' for p in query_params)
    return "{" + body + "}"


def _session_fills(ep: Endpoint) -> list[str]:
    out: list[str] = []
    for p in ep.query_params:
        if p.is_session_id:
            out.append(f"        if {p.name} is None:")
            out.append(f"            {p.name} = _session_id()")
    return out


def _method(ep: Endpoint, *, is_async: bool) -> list[str]:
    kw = "async def" if is_async else "def"
    parts = ["self"] + [f"{p.name}: {p.base_type}" for p in ep.path_params]
    if ep.query_params:
        parts.append("*")
        parts += [_annot(p) for p in ep.query_params]
    out: list[str] = [
        f"    {kw} {ep.name}({', '.join(parts)}) -> {ep.return_type}:"
    ]
    out.append(f'        """{ep.summary}"""')
    if ep.name == "resolve_media":
        out.append("        if (pk is None) == (code is None):")
        out.append("            raise ValueError(")
        out.append(
            '                "resolve_media needs exactly one of pk or code"'
        )
        out.append("            )")
    out += _session_fills(ep)
    await_ = "await " if is_async else ""
    if ep.query_params:
        out.append(
            f'        return {await_}self._request("get", {_path_expr(ep)}, '
            f"params={_params_dict(ep.query_params)})"
        )
    else:
        out.append(
            f'        return {await_}self._request("get", {_path_expr(ep)})'
        )
    return out


def _iter_method(ep: Endpoint, *, is_async: bool) -> list[str]:
    iter_ret = "AsyncIterator" if is_async else "Iterator"
    paginate_fn = "apaginate" if is_async else "paginate"
    parts = ["self"] + [f"{p.name}: {p.base_type}" for p in ep.path_params]
    parts.append("*")
    parts += [_annot(p) for p in ep.query_params if p.name != "cursor"]
    parts.append("max_items: Optional[int] = None")
    sig = f"({', '.join(parts)}) -> {iter_ret}[Any]:"
    out: list[str] = [f"    def iter_{ep.name}{sig}"]
    out += _session_fills(ep)
    args = [p.name for p in ep.path_params]
    args += [
        f"{p.name}={p.name}" for p in ep.query_params if p.name != "cursor"
    ]
    args.append("cursor=cursor")
    call = f"self.{ep.name}({', '.join(args)})"
    await_ = "await " if is_async else ""
    def_fetch = "async def fetch" if is_async else "def fetch"
    out.append(f"        {def_fetch}(cursor: Optional[str]) -> Page:")
    out.append(f"            return {await_}{call}")
    out.append(
        f'        return {paginate_fn}(fetch, item_key="{ep.item_key}", '
        "max_items=max_items)"
    )
    return out


def _render_module(*, is_async: bool, endpoints: list[Endpoint]) -> str:
    client = "BaseAsyncClient" if is_async else "BaseSyncClient"
    mixin = "AsyncEndpoints" if is_async else "SyncEndpoints"
    abc_import = "AsyncIterator" if is_async else "Iterator"
    paginate_fn = "apaginate" if is_async else "paginate"
    kind = "async" if is_async else "sync"

    lines = [
        HEADER.rstrip("\n"),
        "",
        "import uuid",
        f"from collections.abc import {abc_import}",
        "from typing import Any, Optional",
        "",
        f"from ._base import {client}",
        f"from ._pagination import Page, {paginate_fn}",
        "from .types import BalanceResponse, MediaIdResolution",
        "",
        "",
        "def _session_id() -> str:",
        "    return str(uuid.uuid4()).upper()",
        "",
        "",
        f"class {mixin}({client}):",
        f'    """Generated GET endpoints for the {kind} client."""',
    ]
    for ep in endpoints:
        lines.append("")
        lines += _method(ep, is_async=is_async)
        if ep.paginable and ep.name not in _NON_PAGE_CURSOR_ENDPOINTS:
            lines.append("")
            lines += _iter_method(ep, is_async=is_async)
    return "\n".join(lines) + "\n"


def _render_types() -> str:
    lines = [
        HEADER.rstrip("\n"),
        "",
        "from typing import Any, Optional, TypedDict",
        "",
        "",
        "class Page(TypedDict):",
        '    """One page of a cursor-paginated response."""',
        "",
        "    items: list[Any]",
        "    next_cursor: Optional[str]",
        "    has_more: bool",
        "",
        "",
        "class MediaIdResolution(TypedDict):",
        '    """A resolved media identity."""',
        "",
        "    pk: str",
        "    code: str",
        "",
        "",
        "class BalanceResponse(TypedDict):",
        '    """Remaining account balance."""',
        "",
        "    balance_usd: str",
        "    currency: str",
    ]
    return "\n".join(lines) + "\n"


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(word[:1].upper() + word[1:] for word in rest)


def _ts_path_expr(ep: Endpoint) -> str:
    if not ep.path_params:
        return f'"{ep.path}"'
    path = ep.path
    for p in ep.path_params:
        path = path.replace(
            "{" + p.name + "}", "${opts." + _camel(p.name) + "}"
        )
    return f"`{path}`"


def _ts_opts_fields(ep: Endpoint, *, skip_cursor: bool = False) -> list[str]:
    fields = [
        f"{_camel(p.name)}: {_PY_TO_TS[p.base_type]}" for p in ep.path_params
    ]
    for p in ep.query_params:
        if skip_cursor and p.name == "cursor":
            continue
        suffix = "" if p.required else "?"
        fields.append(f"{_camel(p.name)}{suffix}: {_PY_TO_TS[p.base_type]}")
    return fields


def _ts_param(fields: list[str], *, required: bool) -> str:
    opts_type = "{ " + "; ".join(fields) + " }"
    return f"opts: {opts_type}" if required else f"opts: {opts_type} = {{}}"


def _ts_session_fills(ep: Endpoint) -> list[str]:
    out: list[str] = []
    for p in ep.query_params:
        if p.is_session_id:
            c = _camel(p.name)
            out.append(f"    const {c} = opts.{c} ?? sessionId();")
    return out


def _ts_method(ep: Endpoint) -> list[str]:
    fields = _ts_opts_fields(ep)
    required = bool(ep.path_params) or any(p.required for p in ep.query_params)
    ret = _TS_RETURN_TYPES.get(ep.name, _TS_RESULT)
    type_arg = f"<{ret}>" if ep.name in _TS_RETURN_TYPES else ""
    name = _camel(ep.name)
    head = f"  {name}(): Promise<{ret}> {{"
    if fields:
        head = (
            f"  {name}({_ts_param(fields, required=required)}): "
            f"Promise<{ret}> {{"
        )
    out = [head]
    if ep.name == "resolve_media":
        out.append(
            "    if ((opts.pk === undefined) === (opts.code === undefined)) {"
        )
        out.append(
            '      throw new TypeError("resolveMedia needs exactly one of '
            'pk or code");'
        )
        out.append("    }")
    out += _ts_session_fills(ep)
    if ep.query_params:
        out.append(
            f'    return this.request{type_arg}("get", {_ts_path_expr(ep)}, {{'
        )
        for p in ep.query_params:
            c = _camel(p.name)
            value = c if p.is_session_id else f"opts.{c}"
            out.append(f"      {p.name}: {value},")
        out.append("    });")
    else:
        out.append(
            f'    return this.request{type_arg}("get", {_ts_path_expr(ep)});'
        )
    out.append("  }")
    return out


def _ts_iter_method(ep: Endpoint) -> list[str]:
    fields = _ts_opts_fields(ep, skip_cursor=True)
    fields.append("maxItems?: number | null")
    required = bool(ep.path_params) or any(
        p.required for p in ep.query_params if p.name != "cursor"
    )
    name = _camel(ep.name)
    iter_name = "iter" + name[:1].upper() + name[1:]
    out = [
        f"  {iter_name}({_ts_param(fields, required=required)}): "
        f"AsyncIterable<{_TS_RESULT}> {{"
    ]
    out += _ts_session_fills(ep)
    call_entries = [
        f"{_camel(p.name)}: opts.{_camel(p.name)}" for p in ep.path_params
    ]
    for p in ep.query_params:
        c = _camel(p.name)
        if p.name == "cursor":
            call_entries.append("cursor")
        elif p.is_session_id:
            call_entries.append(c)
        else:
            call_entries.append(f"{c}: opts.{c}")
    out.append(
        f"    const fetchPage = (cursor: string | undefined): "
        f"Promise<{_TS_RESULT}> =>"
    )
    out.append(f"      this.{name}({{ {', '.join(call_entries)} }});")
    out.append(
        f'    return paginate(fetchPage, {{ itemKey: "{ep.item_key}", '
        "maxItems: opts.maxItems });"
    )
    out.append("  }")
    return out


def _render_ts_types() -> str:
    lines = [
        TS_HEADER,
        "",
        "export interface Page {",
        "  items: unknown[];",
        "  next_cursor: string | null;",
        "  has_more: boolean;",
        "}",
        "",
        "export interface MediaIdResolution {",
        "  pk: string;",
        "  code: string;",
        "}",
        "",
        "export interface BalanceResponse {",
        "  balance_usd: string;",
        "  currency: string;",
        "}",
    ]
    return "\n".join(lines) + "\n"


def _render_ts_endpoints(endpoints: list[Endpoint]) -> str:
    lines = [
        TS_HEADER,
        "",
        'import { BaseClient, sessionId } from "./base";',
        'import { paginate } from "./pagination";',
        'import type { BalanceResponse, MediaIdResolution } from "./types";',
        "",
        "export class Endpoints extends BaseClient {",
    ]
    for ep in endpoints:
        lines.append("")
        lines += _ts_method(ep)
        if ep.paginable and ep.name not in _NON_PAGE_CURSOR_ENDPOINTS:
            lines.append("")
            lines += _ts_iter_method(ep)
    lines.append("}")
    return "\n".join(lines) + "\n"


def _prettier_format(paths: list[Path]) -> None:
    if not PRETTIER_BIN.exists():
        raise RuntimeError(
            f"prettier not found at {PRETTIER_BIN}; run `npm ci` in js/ first"
        )
    subprocess.run(
        [
            str(PRETTIER_BIN),
            "--config",
            str(_PRETTIER_CONFIG),
            "--write",
            *[str(p) for p in paths],
        ],
        check=True,
        capture_output=True,
    )


def _ruff_format(paths: list[Path]) -> None:
    subprocess.run(
        [
            "ruff",
            "format",
            "--line-length",
            "80",
            "--target-version",
            "py39",
            *[str(p) for p in paths],
        ],
        check=True,
        capture_output=True,
    )


def generate(*, out_dir: Path) -> None:
    """Write the three generated modules into ``out_dir`` and ruff-format."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    endpoints = _build_endpoints()
    (out_dir / "types.py").write_text(_render_types(), encoding="utf-8")
    (out_dir / "_endpoints_sync.py").write_text(
        _render_module(is_async=False, endpoints=endpoints), encoding="utf-8"
    )
    (out_dir / "_endpoints_async.py").write_text(
        _render_module(is_async=True, endpoints=endpoints), encoding="utf-8"
    )
    _ruff_format([out_dir / name for name in _OUTPUT_FILES])


def generate_ts(*, out_dir: Path) -> None:
    """Write the two TypeScript modules into ``out_dir`` and prettier-format."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    endpoints = _build_endpoints()
    (out_dir / "types.ts").write_text(_render_ts_types(), encoding="utf-8")
    (out_dir / "endpoints.ts").write_text(
        _render_ts_endpoints(endpoints), encoding="utf-8"
    )
    _prettier_format([out_dir / name for name in _TS_OUTPUT_FILES])


def main() -> None:
    generate(out_dir=PACKAGE_DIR)
    generate_ts(out_dir=JS_SRC_DIR)


if __name__ == "__main__":
    main()
